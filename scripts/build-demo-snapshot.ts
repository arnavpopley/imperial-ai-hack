// Builds web/src/student/demo/snapshot.json: what the real engines produce for one synthetic student, so the
// /demo page shows genuine scores, sub-scores, clashes and society matches without a session or a server.
// The student is synthetic-robotics-automation-01 from data/cohort.json (invented, not a real person).
//
// Run from the repo root: npx tsx scripts/build-demo-snapshot.ts
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { DEFAULT_WEIGHTS, type StudentProfile } from '@modulematch/shared';
import { loadPathways, loadProgrammeRules, loadSocieties } from '../server/src/db/catalogue.ts';
import { DATASET_FILES, ModulesFile, readDataset, REPO_ROOT, SlotsFile } from '../server/src/db/datasets.ts';
import { rankModules } from '../server/src/engines/scoring.ts';
import { matchSocieties } from '../server/src/engines/societies.ts';
import { findClashes } from '../server/src/engines/timetable.ts';
import cohort from '../data/cohort.json' with { type: 'json' };

const STUDENT_ID = 'synthetic-robotics-automation-01';
const TOP_MODULES = 6;
const TOP_SOCIETIES = 3;

const entry = (cohort as unknown as { students: { profile: StudentProfile; shortlist: string[] }[] }).students.find(
  (s) => s.profile.studentId === STUDENT_ID,
);
if (!entry) throw new Error(`${STUDENT_ID} is not in data/cohort.json`);
const { profile, shortlist } = entry;

const modules = readDataset(DATASET_FILES.modules, ModulesFile).modules;
const slots = readDataset(DATASET_FILES.slots, SlotsFile).slots;
const rules = loadProgrammeRules().find((r) => r.programme === profile.programme && r.year === profile.yearOfStudy);
if (!rules) throw new Error(`No programme rules for ${profile.programme} year ${profile.yearOfStudy}`);

const byId = new Map(modules.map((m) => [m.id, m]));
const ranked = rankModules(profile, modules, DEFAULT_WEIGHTS, rules).filter((r) => r.eligible);
const top = ranked.slice(0, TOP_MODULES).map((r) => {
  const m = byId.get(r.moduleId)!;
  return { id: m.id, code: m.code, title: m.title, ects: m.ects, terms: m.terms, fit: r.fit, sub: r.sub };
});

const shortlisted = shortlist.map((id) => byId.get(id)).filter((m) => m !== undefined);
const clashes = findClashes(shortlist, slots).map((c) => ({
  a: c.moduleA,
  b: c.moduleB,
  probability: c.probability,
  label: c.label,
  term: c.term,
}));
const week = slots
  .filter((s) => shortlist.includes(s.moduleId))
  .map((s) => ({ moduleId: s.moduleId, day: s.day, start: s.start, end: s.end, term: s.term, kind: s.kind }));

const societies = loadSocieties();
const societyById = new Map(societies.map((s) => [s.id, s]));
const societyMatches = matchSocieties(profile, societies)
  .filter((m) => !m.wildcard)
  .sort((a, b) => b.fit - a.fit)
  .slice(0, TOP_SOCIETIES)
  .map((m) => ({ id: m.societyId, name: societyById.get(m.societyId)?.name ?? m.societyId, fit: m.fit, reason: m.reason }));

const pathway = loadPathways().find((p) => profile.pathways.includes(p.id));

const snapshot = {
  _note: `Generated by scripts/build-demo-snapshot.ts from ${STUDENT_ID} in data/cohort.json, using the real scoring, rules, timetable and society engines with the default weights. Synthetic student; regenerate after changing the data or engines.`,
  student: {
    programme: profile.programme,
    year: profile.yearOfStudy,
    interests: profile.interests,
    pathway: pathway ? { id: pathway.id, title: pathway.title } : null,
    style: profile.style,
  },
  weights: DEFAULT_WEIGHTS,
  topModules: top,
  shortlist: shortlisted.map((m) => ({ id: m.id, code: m.code, title: m.title })),
  week,
  clashes,
  societies: societyMatches,
};

const out = resolve(REPO_ROOT, 'web/src/student/demo/snapshot.json');
writeFileSync(out, `${JSON.stringify(snapshot, null, 2)}\n`);
console.log(`Wrote ${out}: ${top.length} modules, ${clashes.length} clashes, ${societyMatches.length} societies`);
