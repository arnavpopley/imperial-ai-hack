// Ranking benchmark personas (docs/ranking-benchmark.md). Forty synthetic MEng Mechanical Engineering Year 3
// students. Each has a description, which is what the student would say in the interview and is all the
// independent judge sees, and the structured profile the extractor would produce from it, which is all the
// scoring engine sees. Values follow the extractor's scale (server/src/agents/extractor.ts): about 0.85-0.95
// for "love", 0.5-0.6 for "quite like" or "maybe", 0.1-0.2 for "avoid" or "prefer the opposite".
// Topics a student never mentions are left out (strength 0), as the extractor would leave them.
import type { PathwayId, StudentProfile, TopicId } from '@modulematch/shared';

/** Traits used to slice the results. A persona can have several. */
export type Trait = 'strong' | 'weak' | 'breadth' | 'exam-averse' | 'null-style' | 'contradictory' | 'multi-pathway' | 'undecided';

type StyleInput = Partial<Record<'exam' | 'group' | 'applied' | 'maths' | 'coding' | 'workload', number>>;

export interface BenchmarkPersona {
  id: string;
  name: string;
  traits: Trait[];
  /** What the student says in the interview, in their own words. The judge sees only this. */
  description: string;
  interests: Record<TopicId, number>;
  pathways: PathwayId[];
  style: StudentProfile['style'];
  breadthAppetite: number | null;
}

const style = (s: StyleInput): StudentProfile['style'] => ({
  examPreference: s.exam ?? null,
  groupPreference: s.group ?? null,
  appliedPreference: s.applied ?? null,
  mathsComfort: s.maths ?? null,
  codingComfort: s.coding ?? null,
  workloadTolerance: s.workload ?? null,
});

